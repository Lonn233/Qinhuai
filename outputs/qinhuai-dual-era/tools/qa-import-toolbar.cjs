const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('C:/Users/Lonn/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const key = 'qinhuai:main-map:toolbar-collapsed:v1';
const url = 'http://127.0.0.1:4180/qinhuai-modern-import.html?time=night&view=riverfront&gateLight=gold';
const out = path.resolve('work/main-map-toolbar-20261019');
fs.mkdirSync(out, {recursive:true});
(async () => {
  const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-gpu-sandbox']});
  try {
    // Fresh isolated contexts; never access the user's live browser data.
    const ui = await browser.newContext({viewport:{width:1200,height:820}});
    await ui.route('**/import-viewer-startup.js*', r => r.fulfill({contentType:'text/javascript',body:'/* UI-only interaction tests */'}));
    const page = await ui.newPage();
    await page.goto(url);
    const toggle = page.locator('#toolbarToggle');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
    await page.evaluate(() => {
      localStorage.setItem('qinhuai.building-light-studies.v1', 'existing saved color schemes');
      document.querySelector('.festival-panel').open = true;
      document.querySelector('#mountainDiameter').value = '14.2';
      document.querySelector('#toolbarContent').scrollTop = 480;
    });
    const scroll = await page.locator('#toolbarContent').evaluate(el => el.scrollTop);
    await toggle.click();
    assert.equal(await page.locator('#toolbarContent').isVisible(), false);
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    let box = await page.locator('#toolbar').boundingBox();
    assert.ok(box.height < 65 && box.width <= 190);
    await toggle.press('Enter');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
    assert.equal(await page.locator('#toolbarContent').evaluate(el => el.scrollTop), scroll);
    assert.equal(await page.locator('#mountainDiameter').inputValue(), '14.2');
    assert.equal(await page.locator('.festival-panel').evaluate(el => el.open), true);
    await toggle.press('Space');
    await page.reload();
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    assert.equal(await page.evaluate(() => localStorage.getItem('qinhuai.building-light-studies.v1')), 'existing saved color schemes');
    await page.setViewportSize({width:390,height:844});
    await toggle.click();
    box = await page.locator('#toolbar').boundingBox();
    assert.ok(box.x + box.width <= 390 && box.height <= 844 * .54 + 1);
    await page.evaluate(k => localStorage.setItem(k, 'corrupt'), key);
    await page.reload();
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
    const denied = await ui.newPage();
    await denied.addInitScript(() => Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Disabled','SecurityError');}}));
    await denied.goto(url);
    await denied.locator('#toolbarToggle').click();
    assert.equal(await denied.locator('#toolbarToggle').getAttribute('aria-expanded'), 'false');
    await denied.locator('#toolbarToggle').click();
    assert.equal(await denied.locator('#toolbarContent').isVisible(), true);
    await ui.close();
    console.log('PASS: desktop/mobile, keyboard, saved collapse state, scroll/form preservation, unrelated presets untouched, unavailable storage');

    const live = await browser.newContext({viewport:{width:1100,height:740},deviceScaleFactor:1});
    const map = await live.newPage();
    map.setDefaultTimeout(60000);
    const errors=[];
    map.on('pageerror', e => errors.push(String(e)));
    map.on('console', m => {if(m.type()==='error') errors.push(m.text());});
    await map.goto(url,{waitUntil:'domcontentloaded',timeout:60000});
    console.log('Loading actual night map...');
    await map.waitForFunction(() => window.__QINHUAI_STARTUP__?.phase === '场景已加载' || window.__QINHUAI_STARTUP__?.error, null, {timeout:240000});
    const state = await map.evaluate(() => ({phase:window.__QINHUAI_STARTUP__.phase,error:window.__QINHUAI_STARTUP__.error,tiles:window.__QINHUAI_IMPORT__?.loadedTileIds,contextLost:window.__QINHUAI_IMPORT__?.renderer.getContext().isContextLost()}));
    assert.equal(state.error,null);
    assert.ok(state.tiles.length > 0);
    assert.equal(state.contextLost,false);
    await map.locator('#toolbarToggle').click();
    assert.equal(await map.locator('#toolbarContent').isVisible(),false);
    await map.screenshot({path:path.join(out,'collapsed.png'),timeout:60000});
    await map.locator('#toolbarToggle').click();
    assert.equal(await map.locator('#loadAll').isVisible(),true);
    await map.screenshot({path:path.join(out,'expanded.png'),timeout:60000});
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(out,'qa.json'), JSON.stringify({passed:true,state,errors},null,2));
    console.log('PASS: actual night map loaded, both menu states, no browser/WebGL errors',state);
    await live.close();
  } finally { await browser.close(); }
})().catch(error => {console.error(error);process.exitCode=1;});
