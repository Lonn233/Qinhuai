import assert from 'node:assert/strict';
import * as THREE from 'three';
import { ImportRenderVisibility, spatialInstanceGroups } from '../import-render-visibility.js';
import { MAP_SCALE, personFar, lampLevel } from '../import-performance-profiles.mjs';

const scene = new THREE.Scene(), root = new THREE.Group(); scene.add(root);
root.rotation.y = Math.PI / 2; root.position.set(30, 4, -10);
const material = new THREE.MeshBasicMaterial();
const near = new THREE.Mesh(new THREE.BoxGeometry(2, 2, 2), material);
const far = new THREE.Mesh(near.geometry, material); far.position.set(200, 0, 0);
const crossing = new THREE.Mesh(new THREE.BoxGeometry(240, 2, 2), material); crossing.position.x = 100;
const authoredHidden = new THREE.Mesh(near.geometry, material); authoredHidden.visible = false;
const spill = new THREE.Mesh(near.geometry, material); spill.frustumCulled = false;
const shaderMesh = new THREE.Mesh(near.geometry, new THREE.ShaderMaterial());
const animated = new THREE.Group(); animated.userData.renderDynamic = true;
const animatedMesh = new THREE.Mesh(near.geometry, material); animated.add(animatedMesh);
root.add(near, far, crossing, authoredHidden, spill, shaderMesh, animated);
root.updateWorldMatrix(true, true);
const before = [near, far, crossing].map(mesh => mesh.matrixWorld.clone());
const visibility = new ImportRenderVisibility();
assert.equal(visibility.register(root), 4);
assert.equal(visibility.register(root), 0, 'idempotent async registration');
const position = new THREE.Vector3(30, 4, -10);
visibility.update(position, 15);
assert.equal(near.parent.visible, true);
assert.equal(far.parent.visible, false);
assert.equal(crossing.parent.visible, true, 'large crossing mesh uses its full world bounds, not center');
assert.equal(authoredHidden.visible, false, 'layer visibility remains authoritative');
assert.equal(spill.parent, root, 'shader-expanded footprints are not culled');
assert.equal(shaderMesh.parent, root);
assert.equal(animatedMesh.parent, animated);
root.updateWorldMatrix(true, true);
[near, far, crossing].forEach((mesh, i) => assert.deepEqual(mesh.matrixWorld.elements, before[i].elements));
// Collision tests explicitly query mesh references, even if a render wrapper is hidden.
const ray = new THREE.Raycaster(new THREE.Vector3(30, 10, -210), new THREE.Vector3(0, -1, 0));
assert.ok(ray.intersectObject(far, false).length > 0, 'render culling does not disable precise collisions');
visibility.update(position, null);
assert.ok([near, far, crossing].every(mesh => mesh.parent.visible), 'orbit/original restores every cell');
visibility.update(position, 15);
assert.equal(far.parent.visible, false, 'culling resumes after orbit');
const late = new THREE.Mesh(near.geometry, material); late.position.x = 400; root.add(late);
visibility.register(root); visibility.update(position, 15);
assert.equal(late.parent.visible, false, 'late-loaded cells are culled without player motion');
visibility.update(new THREE.Vector3(30, 4, -410), 15);
assert.equal(late.parent.visible, true);
assert.equal(near.parent.visible, false);
visibility.dispose();
assert.ok([near, far, crossing, late].every(mesh => mesh.parent === root));
assert.equal(authoredHidden.visible, false);
assert.equal(visibility.stats.cells, 0);

const matrices = [0, 5, 100, -100].map(x => new THREE.Matrix4().makeTranslation(x, 0, 0));
const buckets = [...spatialInstanceGroups(matrices, near.geometry, root.matrixWorld)];
assert.ok(buckets.length >= 3, 'distant instances no longer share one draw batch');
assert.deepEqual(new Set(buckets.flat()), new Set(matrices), 'each exact instance matrix retained once');
assert.equal(personFar('smooth'), 180 * MAP_SCALE);
assert.equal(personFar('low'), 120 * MAP_SCALE);
assert.equal(personFar('original', 1234), 1234);
assert.equal(lampLevel(8.5, 0), 0); assert.equal(lampLevel(9.3, 0), 1);
assert.equal(lampLevel(7, 1), 1); assert.equal(lampLevel(6.7, 1), 0);
console.log('PASS: world bounds, crossing cells, hidden collisions, authored visibility, restore/dispose, late loads, spatial instances and profile thresholds');
