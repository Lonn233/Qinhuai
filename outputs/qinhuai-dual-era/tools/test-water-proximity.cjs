const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const layout = require('../assets/qinhuai-modern-import/festival/layout.json');
const bundle = require('esbuild').buildSync({
  stdin: {contents: "export * from './import-river-system.js';export * as THREE from 'three';export {MAP_SCALE} from './import-performance-profiles.mjs';", resolveDir: root},
  bundle: true, format: 'cjs', platform: 'node', write: false, logLevel: 'silent',
}).outputFiles[0].text;
const mod = {exports: {}};
new Function('module', 'exports', 'require', bundle)(mod, mod.exports, require);
const {RiverSystem, THREE, MAP_SCALE} = mod.exports;
global.innerWidth = 1440;
const scene = new THREE.Scene(), parent = new THREE.Group();
scene.add(parent);
const original = new THREE.Mesh(); original.name = layout.water.node;
const tile = new THREE.Group(); tile.add(original); parent.add(tile);
const river = new RiverSystem({scene, parent, renderer: {}});
assert.equal(river.quality, 'low', 'water defaults to the lowest quality');
assert.deepEqual(river.captureSettings, {size:256,hz:3});
river.setPerformanceOverride({size:256,hz:6});
assert.deepEqual(river.captureSettings, {size:256,hz:3}, 'smooth profile cannot raise low water quality');
river.setQuality('balanced');
assert.deepEqual(river.captureSettings, {size:256,hz:6});
river.setPerformanceOverride(null);
assert.deepEqual(river.captureSettings, {size:512,hz:12}, 'manual higher water quality remains available');
river.setQuality('low');
const points = layout.water.triangles.flat();
const edge = points.reduce((a, b) => b[1] < a[1] ? b : a);
const position = meters => new THREE.Vector3(edge[0], layout.water.height + 2, edge[1] - meters * MAP_SCALE);
let seconds = 0;
const move = meters => river.update(++seconds, 1 / 60, position(meters));
river.registerTile(layout.water.tile, tile);
assert.equal(river.mesh, null);
assert.equal(original.visible, false, 'source water stays hidden until the player reaches shore');
move(40);
assert.equal(river.loaded, false, 'far startup allocates no water resources');
river.setTime('night'); river.setQuality('low'); river.setPerformanceOverride({size: 256, hz: 3});
move(9);
assert.equal(river.loaded, false, 'flow surface stays unloaded outside shoreline radius');
move(7);
assert.equal(river.active, true);
assert.equal(original.visible, false);
assert.equal(river.targets.length, 2);
assert.ok(river.targets.every(target => target?.isRenderTarget && target.width === 256));
assert.equal(river.mesh.material.uniforms.color.value.getHex(), 0x566e83);
const resources = [river.mesh.geometry, river.mesh.material, ...river.maps, ...river.targets];
let disposed = 0;
resources.forEach(resource => resource.addEventListener('dispose', () => disposed++));
move(10); assert.equal(river.active, true, 'hysteresis keeps water loaded in the band');
move(13);
assert.equal(river.loaded, false); assert.equal(river.mesh, null);
assert.equal(disposed, 7, 'geometry, material, three maps and two targets released');
assert.equal(original.visible, false, 'original water remains hidden after leaving the shoreline');
move(10); assert.equal(river.loaded, false, 'hysteresis prevents immediate reload');
move(7); assert.equal(river.active, true);
assert.equal(river.stats.captureHz, 3); assert.equal(river.stats.quality, 'low');
assert.equal(river.mesh.material.uniforms.color.value.getHex(), 0x566e83);
river.setEnabled(false); move(0);
assert.equal(river.loaded, false); assert.equal(original.visible, true);
river.setEnabled(true); assert.equal(river.active, true); assert.equal(original.visible, false);
river.setVisible(false); move(0);
assert.equal(river.loaded, false); assert.equal(original.visible, false);
river.setVisible(true); assert.equal(river.active, true);
river.setWireframe(true); move(0);
assert.equal(river.loaded, false); assert.equal(original.visible, true);
river.setWireframe(false); assert.equal(river.active, true);
for (let i = 0; i < 5; i++) { move(40); move(0); assert.equal(river.targets.length, 2); }
river.failed = true; river.sync(); move(0);
assert.equal(river.loaded, false); assert.equal(original.visible, true);
river.dispose(); original.geometry.dispose(); original.material.dispose();
console.log('PASS: lazy startup, scaled shoreline distance, hysteresis, disposal, reentry, settings, visibility and failure fallback.');
